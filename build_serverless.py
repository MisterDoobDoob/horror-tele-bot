"""Generate tgcloud/lib/config.js from .env for Telegram Serverless.

Serverless code has no environment variables and no filesystem, so this script
bakes the passkeys/replies from .env into a JS module. Local media files are
uploaded to Telegram once (to UPLOAD_CHAT_ID) and replaced by their file_id;
results are cached in .tgcloud-files.json so unchanged files aren't re-uploaded.

Usage:
    python build_serverless.py && npx tgcloud push
"""

import asyncio
import json
import logging
import os
from pathlib import Path
from typing import Any, Mapping

from bot import (
    BASE_DIR,
    ENV_FILE,
    FILE_TYPES,
    Reply,
    TelegramPasskeyBot,
    _resolve_local_file,
    load_env_file,
    load_invalid_reply,
    load_passkey_responses,
)

CONFIG_FILE = BASE_DIR / "tgcloud" / "lib" / "config.js"
CACHE_FILE = BASE_DIR / ".tgcloud-files.json"

CONFIG_HEADER = (
    "// Generated by build_serverless.py from .env. Do not edit by hand.\n"
    "// Contains your passkeys, so it is gitignored.\n"
)


def _extract_file_id(message: dict[str, Any], field: str) -> str:
    """Pull the file_id out of a sent Message (Telegram may store it under another key)."""
    for key in (field, *(f for _, f in FILE_TYPES.values())):
        value = message.get(key)
        if isinstance(value, list) and value:  # photo: list of sizes, largest last
            value = value[-1]
        if isinstance(value, dict) and "file_id" in value:
            return value["file_id"]
    raise RuntimeError(f"No file_id in Telegram response: {message}")


class FileUploader:
    """Uploads local files to a chat to obtain reusable file_ids, with caching."""

    def __init__(self, bot: TelegramPasskeyBot, bot_id: str, chat_id: str, cache: dict) -> None:
        self._bot = bot
        self._chat_id = chat_id
        self._cache: dict[str, str] = cache.setdefault(bot_id, {})  # file_ids are per bot

    async def file_id(self, path: Path, file_type: str) -> str:
        stat = path.stat()
        key = f"{path}|{stat.st_size}|{stat.st_mtime_ns}|{file_type}"
        if key in self._cache:
            return self._cache[key]

        logging.info("Uploading %s as %s", path.name, file_type)
        method, field = FILE_TYPES[file_type]
        result = await self._bot._api_request(
            method,
            {"chat_id": self._chat_id, "disable_notification": "true"},
            files={field: path},
        )
        if not result.get("ok"):
            raise RuntimeError(f"Uploading {path.name} failed: {result}")
        message = result["result"]
        file_id = _extract_file_id(message, field)

        # The upload message was only needed for its file_id; tidy it away.
        await self._bot._api_request(
            "deleteMessage", {"chat_id": self._chat_id, "message_id": message["message_id"]}
        )

        self._cache[key] = file_id
        return file_id


async def _serialize_reply(reply: Reply, uploader: FileUploader | None) -> dict[str, str]:
    out: dict[str, str] = {}
    if reply.text:
        out["text"] = reply.text
    if reply.file:
        file_type = reply.resolved_file_type()
        path = _resolve_local_file(reply.file)
        if path is not None:
            if uploader is None:
                raise RuntimeError("Local files need TELEGRAM_BOT_TOKEN and UPLOAD_CHAT_ID set")
            out["file"] = await uploader.file_id(path, file_type)
        else:
            out["file"] = reply.file  # URL or file_id: Telegram fetches it directly
        out["type"] = file_type
    return out


def render_config(config: dict[str, Any]) -> str:
    # JSON is valid JavaScript, so the config can be emitted as-is.
    return CONFIG_HEADER + "export default " + json.dumps(config, ensure_ascii=False, indent=2) + ";\n"


async def build_config(env: Mapping[str, str], cache: dict) -> dict[str, Any]:
    responses = load_passkey_responses(env)
    invalid = load_invalid_reply(env)

    uploader = None
    needs_upload = any(
        r.file and _resolve_local_file(r.file) for r in (*responses.values(), invalid)
    )
    if needs_upload:
        token = env.get("TELEGRAM_BOT_TOKEN")
        chat_id = (env.get("UPLOAD_CHAT_ID") or "").strip()
        if not token or not chat_id:
            raise RuntimeError(
                "Local files must be uploaded to Telegram first: set TELEGRAM_BOT_TOKEN and "
                "UPLOAD_CHAT_ID (e.g. your own user id, after sending /start to the bot)"
            )
        bot = TelegramPasskeyBot(token=token, responses={})
        uploader = FileUploader(bot, token.split(":", 1)[0], chat_id, cache)

    return {
        "responses": {
            passkey: await _serialize_reply(reply, uploader) for passkey, reply in responses.items()
        },
        "invalid": await _serialize_reply(invalid, uploader),
    }


def main() -> None:
    load_env_file(ENV_FILE)
    cache = json.loads(CACHE_FILE.read_text(encoding="utf-8")) if CACHE_FILE.is_file() else {}
    try:
        config = asyncio.run(build_config(os.environ, cache))
    finally:
        if cache:
            CACHE_FILE.write_text(json.dumps(cache, indent=2) + "\n", encoding="utf-8")

    CONFIG_FILE.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_FILE.write_text(render_config(config), encoding="utf-8")
    logging.info(
        "Wrote %s with %d passkey(s)",
        CONFIG_FILE.relative_to(BASE_DIR),
        len(config["responses"]),
    )


if __name__ == "__main__":
    main()
